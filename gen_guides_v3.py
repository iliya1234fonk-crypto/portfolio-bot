def roles_sheet(name):
    rows = [
        ("owner", "Владелец", "всё, включая управление админами", "★ нельзя удалить или понизить"),
        ("admin", "Администратор", "всё, кроме управления админами", ""),
        ("manager", "Менеджер", "заявки, ответы, отзывы, клиенты", "без цен, рассылок и настроек"),
        ("support", "Поддержка", "только ответы клиентам и заметки", ""),
        ("viewer", "Наблюдатель", "смотреть статистику", "ничего не меняет"),
    ]
    h = 64 + 76 + 82 + 52 + 44 + 5 * 128 + 110 + 130
    img = g.background(W, h)
    g.img_global = img
    d = ImageDraw.Draw(img)
    y = g.header(d, "ТОЛЬКО ДЛЯ АДМИНОВ", "Роли и права", "Что может каждый администратор")
    for role, title, hint, note in rows:
        col = MINT if role == "owner" else (CYAN if role == "admin" else (AMBER if role == "manager" else (GREEN if role == "support" else DIM)))
        ch = 128 if note else 104
        d.rounded_rectangle([M, y, W - M, y + ch], radius=18, fill=(20, 27, 36), outline=(38, 48, 62), width=2)
        d.rectangle([M + 1, y + 16, M + 5, y + ch - 16], fill=col)
        d.text((M + 30, y + 16), title, font=g.fnt(29, 800), fill=INK)
        d.text((M + 30, y + 56), hint, font=g.fnt(21, 400), fill=DIM)
        if note:
            d.text((M + 30, y + 88), note, font=g.fnt(17, 400), fill=(112, 124, 142))
        d.text((W - M - 40 - d.textlength("/" + role, font=g.mono(20)), y + 22), "/" + role, font=g.mono(20), fill=col)
        y += ch + 14
    y += 10
    y = g.tip_banner(d, y, "Менять права можно точечно: /admin_perm CHAT_ID право on|off. Права: panel, stats, tickets, reply, reviews, notes, users, broadcast, settings, export, ban, pay, admins.", MINT)
    g.footer(W, h, 2, 5, MINT)
    p = os.path.join(g.OUT, name)
    img.save(p, quality=94, subsampling=1)
    return p


